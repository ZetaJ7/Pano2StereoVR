"""Write the two Study 2 configs (Mono and Ours sessions) from one definition (docs/Study2_SSQ_Design_20261123.md).

Study 2 (user 11-23 / 11-24): SSQ comparison of Mono and Ours PA, within-participant AB/BA crossover on two days,
20 lab members (S01-S20). One session shows one version only: 12 clips x 3 repetitions = 36 rated clips in a random
order per participant and session (the same clip never twice in a row), after one Mono practice clip (train_outdoor,
identical on both days). Each clip is rated with the Study 1 scales; Part 1 groups have one clip and no replay on
re-rate (allow_review_on_rerate false). Flow: check-in, SSQ S_pre, headset fit, stereo test (as in Study 1, also an
adaptation phase), Part 1, SSQ S_post, end.

The stereo test, timing and alignment blocks are copied from the Study 1 config (StudyTools/study_config.example.json,
frozen bb1755e) so that both studies use the same screening. Run:  python study2_make_configs.py  (writes
study2_config_mono.json and study2_config_ours.json next to this file; deterministic).
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
S1 = json.loads((HERE / "study_config.example.json").read_text(encoding="utf-8"))

STUDY_ID = "Pano2Stereo-Study2-SSQ"
VERSION = "s2-v1-2026-11-24"

# 12 clips (user 11-23: list as in the design table, rin_B kept; user 11-24: near_C and vin_A kept)
CLIPS = [
    ("bnear_A", "near", "indoor", "blender"), ("bnear_B", "near", "indoor", "blender"),
    ("bnear_D", "near", "indoor", "blender"), ("bnear_F", "near", "indoor", "blender"),
    ("near_B", "near", "indoor", "replica"), ("near_C", "near", "indoor", "replica"),
    ("vin_A", "virtual_indoor", "indoor", "replica"), ("vin_C", "virtual_indoor", "indoor", "replica"),
    ("bin_A", "virtual_indoor", "indoor", "blender"),
    ("rin_A", "real_indoor", "indoor", "helvipad"), ("rin_B", "real_indoor", "indoor", "helvipad"),
    ("rin_C", "real_indoor", "indoor", "helvipad"),
]


def config(condition: str) -> dict:
    return {
        "study_id": STUDY_ID,
        "config_version": f"{VERSION}-{condition}",
        "note": ("Study 2 (SSQ, Mono vs Ours PA crossover), session condition " + condition + ". Generated by "
                 "study2_make_configs.py; design: docs/Study2_SSQ_Design_20261123.md. Stereo test, timing and alignment "
                 "copied from the Study 1 config (frozen bb1755e)."),
        "stimuli_dir": "Stimuli_s2",
        "file_pattern": "{folder}/{clip_id}__{condition}.mp4",
        "stimulus_folders": {"part1": {"training": "part1/practice", "main": "part1/{cell}"},
                             "note": "Stimuli_s2: part1/practice (train_outdoor Mono), part1/near (6 near clips), "
                                     "part1/virtual_indoor, part1/real_indoor (6 Study 1 indoor clips)"},
        "flow": ["checkin", "ssq:S_pre", "hmd_fit", "stereotest", "part:1", "ssq:S_post", "end"],
        "min_break_s": S1.get("min_break_s", 120),
        "alignment": S1["alignment"],
        "timing": S1["timing"],
        "stereotest": S1["stereotest"],
        "part1": {
            "conditions": [condition],
            "repetitions": 3,
            "training": [{"clip_id": "train_outdoor", "condition": "mono"}],
            "dummy": [],
            "viewing": {"self_paced": False, "min_view_s": None, "max_view_s": 0, "allow_review_on_rerate": False,
                        "note": "Study 2: one clip per group, no replay on re-rate (design section 3)"},
            "clips": [{"clip_id": c, "cell": cell, "scene": scene, "source": src} for c, cell, scene, src in CLIPS],
        },
    }


def main() -> int:
    for cond in ("mono", "ours"):
        p = HERE / f"study2_config_{cond}.json"
        p.write_text(json.dumps(config(cond), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        print("wrote", p.name)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
